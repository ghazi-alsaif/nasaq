#!/bin/bash
# NASAQ (نَسَق) installer — an opinionated shell layer for Omarchy by GHS.
#   ./install.sh            install (or re-install) NASAQ for this user
#   ./install.sh --yes      also install the optional packages without asking
#   ./install.sh --update   refresh NASAQ's files only (keeps your bar layout; refreshes NASAQ's menu rows)
# Nothing under /usr/share/omarchy is touched. Every file changed is backed up first.
set -euo pipefail
R="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
C="$HOME/.config"; B="$HOME/.local/bin"; S="$HOME/.local/share"
YES=false; UPDATE=false
for a in "$@"; do case $a in --yes) YES=true ;; --update) UPDATE=true ;; esac; done
say() { printf '\033[32m ✓\033[0m %s\n' "$1"; }
warn() { printf '\033[33m !\033[0m %s\n' "$1" >&2; }

command -v omarchy >/dev/null || { echo "NASAQ needs Omarchy 4.x."; exit 1; }
ver=$(omarchy version 2>/dev/null | cut -d- -f1)
[[ $(printf '%s\n4.0.4\n' "$ver" | sort -V | head -1) == 4.0.4 ]] || { echo "NASAQ needs Omarchy 4.0.4 or newer (found $ver)."; exit 1; }
command -v quickshell >/dev/null || { echo "Quickshell is missing."; exit 1; }

backup="$HOME/.local/state/nasaq/install-backup-$(date +%Y%m%d-%H%M%S)"
mkdir -p "$backup"
for f in omarchy/shell.json hypr/hyprland.lua hypr/looknfeel.lua hypr/bindings.lua omarchy/extensions/omarchy-menu.jsonc; do
  if [[ -f $C/$f ]]; then mkdir -p "$backup/$(dirname "$f")"; cp "$C/$f" "$backup/$f"; fi
done
# uninstall.sh restores the backup taken before NASAQ first touched these
# files, so a reinstall or --update must not repoint it at an already-NASAQ copy.
ptr="$HOME/.local/state/nasaq/last-install-backup"
[[ -d $(cat "$ptr" 2>/dev/null) ]] || echo "$backup" > "$ptr"
say "backup in ${backup/#$HOME/\~}"

# Files
mkdir -p "$C/omarchy/plugins" "$C/hypr" "$B" "$S/omarchy-overrides" "$S/sounds/nasaq" "$C/omarchy/nasaq" \
  "$C/omarchy/hooks/theme-set.d" "$C/omarchy/hooks/post-update.d"
for d in "$R"/plugins/nasaq.*/; do rsync -a --delete "$d" "$C/omarchy/plugins/$(basename "$d")/"; done
cp "$R"/hypr/nasaq-*.lua "$C/hypr/"
for g in nasaq-env nasaq-monitors nasaq-rules nasaq-corners nasaq-binds-arabic nasaq-scratchpads nasaq-windows nasaq-desktop; do
  [[ -f $C/hypr/$g.lua ]] || printf -- '-- Generated by NASAQ Settings — do not edit by hand.\n' > "$C/hypr/$g.lua"
done
cp "$R/defaults/nasaq-binds.lua" "$C/hypr/nasaq-binds.lua"
grep -qs 'return' "$C/hypr/nasaq-remap.lua" || printf 'return {\n}\n' > "$C/hypr/nasaq-remap.lua"
install -m755 "$R"/bin/* "$B/"
install -m755 "$R/overrides/omarchy-launch-screensaver" "$S/omarchy-overrides/"
rsync -a "$R/overrides/screensaver-matrix/" "$S/screensaver-matrix/"
ln -sf "$S/screensaver-matrix/omarchy-screensaver-matrix" "$S/omarchy-overrides/omarchy-screensaver"
rsync -a "$R/sounds/" "$S/sounds/nasaq/"
install -m755 "$R"/hooks/theme-set.d/* "$C/omarchy/hooks/theme-set.d/"
install -m755 "$R"/hooks/post-update.d/* "$C/omarchy/hooks/post-update.d/"
rsync -a "$R/help/" "$C/omarchy/nasaq/help/"
for f in island.json windows.json windows-default.json; do
  [[ -f $C/omarchy/nasaq/$f ]] || cp "$R/defaults/$f" "$C/omarchy/nasaq/$f"
done
# The doctor (bin/nasaq-doctor) compares against these after Omarchy updates.
mkdir -p "$C/omarchy/nasaq/defaults"
cp "$R/defaults/shell.json.patch.json" "$R/defaults/menu-entries.jsonc" "$C/omarchy/nasaq/defaults/"
# nasaq-doctor runs the clone check now; the old separate hook would notify twice.
rm -f "$C/omarchy/hooks/post-update.d/nasaq-clone-check.sh"
# Omarchy's Update › Config › Hyprland resets ~/.config/hypr without running the
# post-update hooks; a watcher on hyprland.lua runs the doctor after any rewrite.
mkdir -p "$C/systemd/user"
cat > "$C/systemd/user/nasaq-doctor.path" <<'EOF'
[Unit]
Description=NASAQ: put NASAQ back when ~/.config/hypr/hyprland.lua is rewritten

[Path]
PathChanged=%h/.config/hypr/hyprland.lua
Unit=nasaq-doctor.service

[Install]
WantedBy=default.target
EOF
cat > "$C/systemd/user/nasaq-doctor.service" <<'EOF'
[Unit]
Description=NASAQ doctor (repair after a Hyprland config reset)

[Service]
Type=oneshot
# Give a refresh that rewrites several files a moment to finish.
ExecStartPre=/bin/sleep 3
ExecStart=%h/.local/bin/nasaq-doctor --fix --notify-changes
EOF
systemctl --user daemon-reload >/dev/null 2>&1 || true
systemctl --user enable --now nasaq-doctor.path >/dev/null 2>&1 || warn "could not enable the Hyprland watcher (nasaq-doctor.path)"
say "files installed"

# Hyprland: one line in each of your own files loads NASAQ's modules.
hl="$C/hypr/hyprland.lua"
if ! grep -q 'nasaq-pre.lua' "$hl"; then
  python3 - "$hl" <<'PY'
import sys
p = sys.argv[1]; s = open(p).read()
line = 'pcall(dofile, (os.getenv("HOME") or "") .. "/.config/hypr/nasaq-pre.lua")  -- NASAQ\n'
key = 'require("default.hypr.omarchy")'
s = s.replace(key, line + key, 1) if key in s else line + s
s += '\npcall(dofile, (os.getenv("HOME") or "") .. "/.config/hypr/nasaq-post.lua")  -- NASAQ\n'
open(p, "w").write(s)
PY
fi
grep -qs 'nasaq-looknfeel.lua' "$C/hypr/looknfeel.lua" || printf '\npcall(dofile, (os.getenv("HOME") or "") .. "/.config/hypr/nasaq-looknfeel.lua")  -- NASAQ\n' >> "$C/hypr/looknfeel.lua"
grep -qs 'nasaq-bindings.lua' "$C/hypr/bindings.lua" || printf '\npcall(dofile, (os.getenv("HOME") or "") .. "/.config/hypr/nasaq-bindings.lua")  -- NASAQ\n' >> "$C/hypr/bindings.lua"
say "Hyprland hooks in place"

if ! $UPDATE; then
  python3 - "$C/omarchy/shell.json" "$R/defaults/shell.json.patch.json" <<'PY'
import json, os, sys
p, patch = sys.argv[1], json.load(open(sys.argv[2]))
d = json.load(open(p)) if os.path.exists(p) else {"version": 1}
d["bar"] = patch["bar"]
keep = [x for x in d.get("plugins", []) if (x.get("id") if isinstance(x, dict) else x) not in patch["plugins"]]
d["plugins"] = keep + [{"id": i} for i in patch["plugins"]]
d["disabledPlugins"] = sorted(set(d.get("disabledPlugins", [])) | set(patch["disabledPlugins"]))
d["cloneSourceRestores"] = patch["cloneSourceRestores"]
open(p, "w").write(json.dumps(d, indent=2) + "\n")
PY
  say "bar layout set up"
fi

# Omarchy menu: NASAQ's block (between its markers) is replaced on every run,
# so an update brings new rows and the order ... NASAQ, About, System.
menu="$C/omarchy/extensions/omarchy-menu.jsonc"
[[ -f $menu ]] || printf '{\n}\n' > "$menu"
python3 - "$menu" "$R/defaults/menu-entries.jsonc" <<'PY'
import re, sys
p = sys.argv[1]; s = open(p).read(); add = open(sys.argv[2]).read()
s = re.sub(r"[ \t]*// NASAQ \(added by.*?// /NASAQ[ \t]*\n?", "", s, flags=re.S)
i = s.rstrip().rfind("}"); head = s[:i].rstrip()
s = head + ("\n" if head.endswith((",", "{")) else ",\n") + add + "}\n"
open(p, "w").write(s)
PY
say "menu entries in place"

# Optional packages
opt=(tesseract-data-ara cava nwg-displays kitty ptyxis libqalculate)
missing=()
for p in "${opt[@]}"; do pacman -Q "$p" >/dev/null 2>&1 || missing+=("$p"); done
if ((${#missing[@]})); then
  if $YES || { command -v gum >/dev/null && gum confirm "Install optional packages: ${missing[*]}?"; }; then
    omarchy pkg add "${missing[@]}"
  else
    warn "optional, not installed: ${missing[*]}"
  fi
fi

# The app switcher reads the Alt key from the kernel (Hyprland never reports a
# modifier's release). That needs read access to /dev/input: one udev rule.
if [[ ! -f /etc/udev/rules.d/69-nasaq-input.rules ]]; then
  if $YES || { command -v gum >/dev/null && gum confirm "Install the udev rule that lets the app switcher read the Alt key (needs sudo)?"; }; then
    sudo install -m644 "$R/defaults/69-nasaq-input.rules" /etc/udev/rules.d/69-nasaq-input.rules &&
      sudo udevadm control --reload && sudo udevadm trigger --subsystem-match=input --action=add && say "udev rule installed"
  else
    warn "without the udev rule ALT+TAB uses a timing fallback"
  fi
fi

# Optional: the NASAQ login screen (SDDM theme following the Omarchy theme,
# see login/install-login.sh for the files and the one sudoers rule). Offered while it is not
# installed (--update too); once installed it is refreshed when the repository's
# copy changed.
if [[ ! -f /etc/sddm.conf.d/zz-nasaq-login.conf ]]; then
  if $YES || { command -v gum >/dev/null && gum confirm "Install the NASAQ login screen (SDDM theme, needs sudo)?"; }; then
    "$R/login/install-login.sh" || warn "login screen not installed"
  else
    warn "optional, not installed: the NASAQ login screen (later: login/install-login.sh)"
  fi
elif ! cmp -s "$R/login/nasaq-login/Main.qml" /usr/share/sddm/themes/nasaq-login/Main.qml ||
     ! cmp -s "$R/login/nasaq-login/MatrixRain.qml" /usr/share/sddm/themes/nasaq-login/MatrixRain.qml ||
     ! cmp -s "$R/bin/nasaq-login-sync" /usr/local/bin/nasaq-login-sync; then
  "$R/login/install-login.sh" || warn "login screen not refreshed"
fi

# Optional: the NASAQ boot and shutdown screens (Plymouth, following the theme
# like the login screen; see login/install-plymouth.sh). Offered while not
# installed; refreshed when the repository's templates changed.
if command -v plymouth-set-default-theme >/dev/null; then
  # "Installed" means selected too: a folder left by an interrupted install, or
  # another theme chosen since, counts as not installed and is offered again.
  if [[ ! -d /usr/share/plymouth/themes/nasaq || $(plymouth-set-default-theme 2>/dev/null) != nasaq ]]; then
    if $YES || { command -v gum >/dev/null && gum confirm "Install the NASAQ boot and shutdown screens (Plymouth, needs sudo, rebuilds the boot image)?"; }; then
      "$R/login/install-plymouth.sh" || warn "boot screens not installed"
    else
      warn "optional, not installed: the NASAQ boot screens (later: login/install-plymouth.sh)"
    fi
  elif ! cmp -s "$R/login/nasaq-plymouth/nasaq.script.in" /usr/share/plymouth/themes/nasaq/templates/nasaq.script.in ||
       ! cmp -s "$R/bin/nasaq-login-sync" /usr/local/bin/nasaq-login-sync; then
    "$R/login/install-plymouth.sh" || warn "boot screens not refreshed"
  fi
fi

# Optional: system info (fastfetch) when a terminal opens. Never overwrites an
# existing ~/.config/fastfetch; the ~/.bashrc block sits between markers so
# uninstall.sh can take exactly it out again.
if ! grep -qs '# >>> NASAQ fastfetch >>>' "$HOME/.bashrc"; then
  if $YES || { command -v gum >/dev/null && gum confirm "Show system info (fastfetch) when a terminal opens?"; }; then
    command -v fastfetch >/dev/null || omarchy pkg add fastfetch || true
    if command -v fastfetch >/dev/null; then
      [[ -e $C/fastfetch ]] || { mkdir -p "$C/fastfetch" && cp "$R"/fastfetch/* "$C/fastfetch/"; }
      [[ ! -s $HOME/.bashrc || $(tail -c1 "$HOME/.bashrc") == "" ]] || echo >> "$HOME/.bashrc"
      cat >> "$HOME/.bashrc" <<'EOF'
# >>> NASAQ fastfetch >>>
# System info when a terminal opens (added by NASAQ's install.sh, removed by uninstall.sh).
if [[ $- == *i* && -t 1 ]] && command -v fastfetch >/dev/null; then
  if [[ -f ~/.config/fastfetch/compact.jsonc ]]; then fastfetch -c ~/.config/fastfetch/compact.jsonc; else fastfetch; fi
fi
# <<< NASAQ fastfetch <<<
EOF
      say "terminal greeting added to ~/.bashrc"
    else
      warn "fastfetch is not installed, so no terminal greeting"
    fi
  else
    warn "optional, not installed: the terminal greeting (fastfetch)"
  fi
fi

nasaq-arabic-binds on >/dev/null 2>&1 || true
nasaq-scratch apply >/dev/null 2>&1 || true
omarchy-shell -q shell rescanPlugins || true
hyprctl reload >/dev/null 2>&1 || true
$UPDATE || omarchy restart shell >/dev/null 2>&1 || true
say "NASAQ is installed. Open its settings with SUPER + ALT + N."
