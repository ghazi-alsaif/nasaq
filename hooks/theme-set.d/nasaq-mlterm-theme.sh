#!/bin/bash
# Omarchy theme-set hook: mirror the active theme into mlterm.
#
# Omarchy generates terminal colors for alacritty, foot, kitty and ghostty from
# the theme's colors.toml, but ships no template for mlterm. This hook fills the
# gap: it writes ~/.mlterm/color from whatever theme is now active and updates
# bg_color/fg_color in ~/.mlterm/main, so mlterm tracks `omarchy theme set` like
# the terminals Omarchy themes natively. Running windows are updated in place
# through mlterm's OSC 5379 config protocol.

set -euo pipefail

COLORS="$HOME/.local/state/omarchy/current/theme/colors.toml"
MLDIR="$HOME/.mlterm"
MAIN="$MLDIR/main"
COLORFILE="$MLDIR/color"

command -v mlterm >/dev/null 2>&1 || exit 0
[[ -f $COLORS ]] || exit 0

# Read a key out of the flat colors.toml; second argument is the fallback.
color() {
  local value
  value=$(sed -n "s/^$1[[:space:]]*=[[:space:]]*\"\([^\"]*\)\".*/\1/p" "$COLORS" | head -1)
  echo "${value:-$2}"
}

bg=$(color background "#1e1e2e")
fg=$(color foreground "#cdd6f4")
black=$(color darker_background "$bg")
bright_black=$(color muted "#585b70")
white=$(color light_foreground "$fg")
bright_white=$(color bright_foreground "$fg")

red=$(color red "#f38ba8")
green=$(color green "#a6e3a1")
yellow=$(color yellow "#f9e2af")
blue=$(color blue "#89b4fa")
magenta=$(color magenta "#f5c2e7")
cyan=$(color cyan "#94e2d5")

# Bright variants are optional in a theme; fall back to the base hue.
bright_red=$(color bright_red "$red")
bright_green=$(color bright_green "$green")
bright_yellow=$(color bright_yellow "$yellow")
bright_blue=$(color bright_blue "$blue")
bright_magenta=$(color bright_magenta "$magenta")
bright_cyan=$(color bright_cyan "$cyan")

mkdir -p "$MLDIR"

cat >"$COLORFILE" <<EOF
# Generated by the Omarchy theme-set hook. Edits are overwritten on theme change.
black=$black
red=$red
green=$green
yellow=$yellow
blue=$blue
magenta=$magenta
cyan=$cyan
white=$white
hl_black=$bright_black
hl_red=$bright_red
hl_green=$bright_green
hl_yellow=$bright_yellow
hl_blue=$bright_blue
hl_magenta=$bright_magenta
hl_cyan=$bright_cyan
hl_white=$bright_white
EOF

# Update background/foreground in main without disturbing the other settings.
touch "$MAIN"
set_key() {
  local key=$1 value=$2
  if grep -q "^$key[[:space:]]*=" "$MAIN"; then
    sed -i "s|^$key[[:space:]]*=.*|$key = $value|" "$MAIN"
  else
    printf '%s = %s\n' "$key" "$value" >>"$MAIN"
  fi
}
set_key bg_color "$bg"
set_key fg_color "$fg"

# Repaint windows that are already open. mlterm accepts configuration over OSC
# 5379 on its own pty, so write the sequence to each running mlterm's terminal.
for pid in $(pgrep -x mlterm 2>/dev/null || true); do
  for fd in /proc/"$pid"/fd/*; do
    target=$(readlink "$fd" 2>/dev/null) || continue
    case $target in
      /dev/pts/*)
        printf '\033]5379;bg_color=%s\007\033]5379;fg_color=%s\007' "$bg" "$fg" \
          >"$target" 2>/dev/null || true
        break
        ;;
    esac
  done
done

exit 0
